"""Generate runtime contracts from the active dataset; explicit trash_bin rename."""
import argparse
import csv
import json
import shutil
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
ML=ROOT/'magicvision_ml_improvement'
APP=ROOT/'01_app_magicvision_final/app_flutter_magicvision'


def write_json(path,value):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')


def run(migrate=False):
    active_path=ML/'configs/active_dataset.json'
    active=json.loads(active_path.read_text(encoding='utf-8'))
    mapping_path=ROOT/active['class_mapping']
    mapping=json.loads(mapping_path.read_text(encoding='utf-8'))
    if migrate and mapping['names'][10]=='trash_bin':
        # Back up metadata only; numeric YOLO labels and image pixels do not change.
        paths=[mapping_path,ROOT/active['classes'],active_path,
               mapping_path.parent/'distribution.csv',mapping_path.parent/'quality.json']
        backup=ML/'reports/contract_before_trash_can'
        backup.mkdir(parents=True,exist_ok=True)
        for path in paths:
            target=backup/path.name
            if not target.exists():shutil.copy2(path,target)
        mapping['names'][10]='trash_can'
        mapping['name_migration']={'id':10,'from':'trash_bin','to':'trash_can','reason':'Explicit user specification; numeric IDs unchanged'}
        write_json(mapping_path,mapping)
        (ROOT/active['classes']).write_text('\n'.join(mapping['names'])+'\n',encoding='utf-8')
        dist=mapping_path.parent/'distribution.csv'
        with dist.open(encoding='utf-8',newline='') as stream:rows=list(csv.DictReader(stream));fields=list(rows[0])
        for row in rows:
            if row['id']=='10':row['class']='trash_can'
        with dist.open('w',encoding='utf-8',newline='') as stream:
            writer=csv.DictWriter(stream,fields);writer.writeheader();writer.writerows(rows)
        quality=mapping_path.parent/'quality.json';q=json.loads(quality.read_text(encoding='utf-8'))
        q['classes'][10]['class']='trash_can';q['name_migration']=mapping['name_migration'];write_json(quality,q)
    names=mapping['names']
    if len(names)!=22 or names[10]!='trash_can' or names[18:]!=['construction_barrier','handrail','cone','fire_extinguisher']:
        raise ValueError('Active contract differs from the explicitly requested 22 IDs')
    active['names']=names;active['name_aliases']={'trash_bin':'trash_can'};write_json(active_path,active)
    generated='# Generated by sync_campus22_contract.py from active_dataset.json and class_mapping.json.\n'
    (APP/'backend/lambda/campus_contract.py').write_text(generated+'LABELS = '+repr(names)+'\nTAXONOMY = '+repr(active['taxonomy'])+'\n',encoding='utf-8')
    write_json(APP/'backend/sagemaker/campus_contract.json',{'taxonomy':active['taxonomy'],'names':names})
    dart='// Generated from the active dataset; do not edit independently.\nconst campusClassNames = <String>[\n'+''.join('  '+json.dumps(n)+',\n' for n in names)+'];\n'
    dart+='const campusTaxonomy = "'+active['taxonomy']+'";\n'
    policy=json.loads((ML/'configs/detection_depth_policy.json').read_text(encoding='utf-8'))
    dart+='const campusPolicyJson = r\'\'\''+json.dumps(policy,ensure_ascii=False)+'\'\'\';\n'
    target=APP/'lib/core/config/campus_contract.dart';target.write_text(dart,encoding='utf-8')
    write_json(APP/'backend/sagemaker/detection_depth_policy.json',policy)
    print(json.dumps({'taxonomy':active['taxonomy'],'classes':len(names),'class10':names[10]}))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--migrate-trash-can',action='store_true')
    run(parser.parse_args().migrate_trash_can)
